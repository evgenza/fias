func main() {
	out := flag.String("out", "internal/gar/record", "каталог результата")
	verify := flag.Bool("verify", false, "не писать файлы, только сверить содержимое")
	flag.Parse()
	files, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gar-gen-records:", err)
		os.Exit(1)
	}
	for name, data := range files {
		path := *out + "/" + name
		if *verify {
			current, err := os.ReadFile(path)
			if err != nil {
				fmt.Fprintln(os.Stderr, "gar-gen-records:", err)
				os.Exit(1)
			}
			if !bytes.Equal(current, data) {
				fmt.Fprintf(os.Stderr, "gar-gen-records: %s устарел, запустите go generate .\n", path)
				os.Exit(1)
			}
			continue
		}
		if err := os.WriteFile(path, data, 0644); err != nil {
			fmt.Fprintln(os.Stderr, "gar-gen-records:", err)
			os.Exit(1)
		}
	}
}

func generate() (map[string][]byte, error) {
	records, err := recordsSource()
	if err != nil {
		return nil, err
	}
	handler, err := handlerSource()
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"records_gen.go": records,
		"handler_gen.go": handler,
	}, nil
}

// recordsSource формирует описания структур записей из Ent-моделей.
func recordsSource() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/gar-gen-records from Ent models; DO NOT EDIT.\n")
	b.WriteString("//\n// Типизированные записи ГАР: поля и теги повторяют Ent-модели хранения,\n")
	b.WriteString("// но пакет не зависит от ORM. Перегенерация: go generate .\n\n")
	b.WriteString("package record\n\n")
	b.WriteString("import \"gar-importer/internal/gartype\"\n\n")
	for _, entity := range entities {
		model := reflect.TypeOf(entity.Model)
		fmt.Fprintf(&b, "// %s — запись формата %s.\ntype %s struct {\n", entity.Name, entity.Kind, entity.Name)
		for i := 0; i < model.NumField(); i++ {
			field := model.Field(i)
			if field.PkgPath != "" {
				continue // неэкспортируемое (встроенный config Ent)
			}
			tag := string(field.Tag)
			if tag == "" {
				return nil, fmt.Errorf("%s.%s: нет struct-тега", entity.Name, field.Name)
			}
			typeName, err := recordType(field.Type)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %v", entity.Name, field.Name, err)
			}
			fmt.Fprintf(&b, "\t%s %s `%s`\n", field.Name, typeName, tag)
		}
		b.WriteString("}\n\n")
	}
	return formatSource(b.String())
}

// handlerSource формирует интерфейс обработчика и диспетчер потокового декодирования.
func handlerSource() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/gar-gen-records; DO NOT EDIT.\n")
	b.WriteString("//\n// Обработчик типизированных записей и диспетчер по формату.\n\n")
	b.WriteString("package record\n\n")
	b.WriteString(`import (
	"context"
	"encoding/xml"
	"fmt"
	"io"

	"gar-importer/internal/gar"
	"gar-importer/internal/garxml"
)

// Handler получает типизированные записи одного потока декодирования.
// Реализация обязана обрабатывать только методы своего формата.
type Handler interface {
`)
	for _, entity := range entities {
		fmt.Fprintf(&b, "\t%s(context.Context, %s) error\n", entity.Name, entity.Name)
	}
	b.WriteString("}\n\n")
	b.WriteString(`// DecodeStream декодирует XML-документ по записям, проверяет атрибуты
// по спецификации формата и передаёт записи обработчику. Реализация
// обработчика сама отвечает за пакетирование и запись.
func DecodeStream(ctx context.Context, reader io.Reader, kind gar.Kind, limit int64, handler Handler) (garxml.DecodeResult, error) {
	spec, ok := gar.Spec(kind)
	if !ok {
		return garxml.DecodeResult{}, fmt.Errorf("нет спецификации записи для формата %s", kind)
	}
	switch kind {
`)
	for _, entity := range entities {
		fmt.Fprintf(&b, `	case gar.Kind%[1]s:
		return garxml.DecodeXML(ctx, reader, kind, limit, func(decoder *xml.Decoder, start xml.StartElement) error {
			if err := gar.ValidateRecord(kind, spec, start); err != nil {
				return err
			}
			var record %[2]s
			if err := decoder.DecodeElement(&record, &start); err != nil {
				return &gar.RecordError{Kind: kind, Cause: err.Error()}
			}
			return handler.%[2]s(ctx, record)
		})
`, entity.Const, entity.Name)
	}
	b.WriteString(`	default:
		return garxml.DecodeResult{}, fmt.Errorf("unknown GAR format %q", kind)
	}
}
`)
	return formatSource(b.String())
}

// recordType отображает тип поля Ent-модели на тип записи.
func recordType(t reflect.Type) (string, error) {
	if t.PkgPath() == "gar-importer/internal/gartype" {
		return "gartype." + t.Name(), nil
	}
	if t.Kind() == reflect.Pointer {
		elem, err := recordType(t.Elem())
		if err != nil {
			return "", err
		}
		return "*" + elem, nil
	}
	switch t.Kind() {
	case reflect.Int64:
		return "int64", nil
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "bool", nil
	}
	return "", fmt.Errorf("неподдерживаемый тип поля %s", t.Kind())
}

func formatSource(src string) ([]byte, error) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return nil, errors.Join(fmt.Errorf("форматирование сгенерированного кода: %w", err), err)
	}
	return formatted, nil
}
