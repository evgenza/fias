// Команда gar-gen-records генерирует internal/gar/record — независимые
// типизированные записи ГАР и обработчик потокового декодирования.
//
// Записи отражают поля и XML/JSON-теги сгенерированных Ent-моделей;
// зависимость от Ent существует только на этапе генерации: сгенерированный
// пакет record импортирует лишь gartype, gar и garxml.
//
//	go generate .   # из корня репозитория
