// Package control — служебный журнал импорта в схеме gar_control:
// datasets, import_runs, import_files, publications. Состояние выполнения
// импорта отделяется от состояния публикации; данные и checkpoint фиксируются
// одной транзакцией (см. internal/storage: адаптер пишет raw-строки и
// обновляет import_files в одном commit).
package control

import (
	"context"
	"database/sql"
	"fmt"
	"time"

	"gar-importer/internal/importjob"
)

// Schema — служебная схема управления.
const Schema = "gar_control"

// RunState — состояния запуска импорта.
type RunState string

const (
	RunPlanned  RunState = "planned"
	RunLoading  RunState = "loading"
	RunReady    RunState = "ready"
	RunFailed   RunState = "failed"
	RunCanceled RunState = "canceled"
	RunSampled  RunState = "sampled" // пробный запуск; публикацию не разрешает
)

// Mode — режим запуска: полный снимок или проба (limit per file).
type Mode string

const (
	ModeSnapshot Mode = "snapshot"
	ModeSample   Mode = "sample"
)

// Dataset — именованная область данных; сейчас единственная legacy-схема gar.
type Dataset struct {
	ID            int64
	SchemaName    string
	Scope         string
	State         string
	SourceRelease string
	AppliedReleas string
}

// Journal — журнал выполнения импорта.
type Journal struct {
	db *sql.DB
}

// Open гарантирует существование служебных таблиц (CREATE IF NOT EXISTS:
// схема управления приложением, не прикладная история).
func Open(ctx context.Context, db *sql.DB) (*Journal, error) {
	statements := []string{
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s.datasets (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			schema_name text NOT NULL UNIQUE,
			scope text NOT NULL DEFAULT 'full',
			state text NOT NULL DEFAULT 'active',
			source_release text NULL,
			applied_release text NULL,
			created_at timestamptz NOT NULL DEFAULT now()
		)`, Schema),
		fmt.Sprintf(`ALTER TABLE %s.datasets ADD COLUMN IF NOT EXISTS pending_digest text`, Schema),
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s.import_runs (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			dataset_id bigint NOT NULL REFERENCES %s.datasets(id),
			mode text NOT NULL,
			source_path text NOT NULL,
			source_digest text NOT NULL,
			base_release text NULL,
			target_release text NULL,
			options jsonb NOT NULL DEFAULT '{}'::jsonb,
			program_version text NOT NULL DEFAULT 'dev',
			state text NOT NULL DEFAULT 'planned',
			started_at timestamptz NOT NULL DEFAULT now(),
			finished_at timestamptz NULL,
			error text NULL
		)`, Schema, Schema),
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s.import_files (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			run_id bigint NOT NULL REFERENCES %s.import_runs(id),
			entry_path text NOT NULL,
			entry_index int NOT NULL,
			kind text NOT NULL,
			source text NOT NULL,
			region int NOT NULL DEFAULT 0,
			entry_date text NOT NULL DEFAULT '',
			entry_sequence text NOT NULL DEFAULT '',
			decoded bigint NOT NULL DEFAULT 0,
			committed_input bigint NOT NULL DEFAULT 0,
			write_ops bigint NOT NULL DEFAULT 0,
			last_committed_record bigint NOT NULL DEFAULT 0,
			integrity_checked boolean NOT NULL DEFAULT false,
			state text NOT NULL DEFAULT 'loading',
			error text NULL,
			UNIQUE (run_id, entry_path)
		)`, Schema, Schema),
		fmt.Sprintf(`DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = '%s' AND table_name = 'import_files' AND column_name = 'decoded' AND data_type = 'integer') THEN
 ALTER TABLE %s.import_files ALTER COLUMN decoded TYPE bigint;
 END IF;
 END $$`, Schema, Schema),
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s.publications (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name text NOT NULL UNIQUE,
			active_dataset_id bigint NULL REFERENCES %s.datasets(id),
			version bigint NOT NULL DEFAULT 0
		)`, Schema, Schema),
	}
	for _, statement := range statements {
		if _, err := db.ExecContext(ctx, statement); err != nil {
			return nil, fmt.Errorf("control: инициализация таблиц: %w", err)
		}
	}
	return &Journal{db: db}, nil
}

// ensureDataset возвращает dataset для схемы данных; legacy-схема gar
// регистрируется при первом использовании, без переименований и удаления.
func (j *Journal) ensureDataset(ctx context.Context, schemaName string) (int64, error) {
	var id int64
	err := j.db.QueryRowContext(ctx,
		fmt.Sprintf("SELECT id FROM %s.datasets WHERE schema_name = $1", Schema), schemaName).Scan(&id)
	if err == nil {
		return id, nil
	}
	if err != sql.ErrNoRows {
		return 0, err
	}
	err = j.db.QueryRowContext(ctx,
		fmt.Sprintf(`INSERT INTO %s.datasets (schema_name, scope, state) VALUES ($1, 'full', 'legacy') ON CONFLICT (schema_name) DO UPDATE SET schema_name = EXCLUDED.schema_name RETURNING id`, Schema),
		schemaName).Scan(&id)
	if err != nil {
		return 0, fmt.Errorf("control: регистрация dataset %s: %w", schemaName, err)
	}
	return id, nil
}

// StartRun фиксирует начало запуска: источник идентифицируется криптографическим
// digest содержимого (не именем/датой/размером).
func (j *Journal) StartRun(ctx context.Context, schemaName, mode, sourcePath, sourceDigest, programVersion, options string) (int64, error) {
	datasetID, err := j.ensureDataset(ctx, schemaName)
	if err != nil {
		return 0, err
	}
	var runID int64
	err = j.db.QueryRowContext(ctx,
		fmt.Sprintf(`INSERT INTO %s.import_runs (dataset_id, mode, source_path, source_digest, options, program_version, state)
			VALUES ($1, $2, $3, $4, $5::jsonb, $6, $7) RETURNING id`, Schema),
		datasetID, mode, sourcePath, sourceDigest, options, programVersion, string(RunLoading)).Scan(&runID)
	if err != nil {
		return 0, fmt.Errorf("control: создание запуска: %w", err)
	}
	return runID, nil
}

// FinishRun закрывает запуск: ready для полного импорта, sampled для пробы,
// failed/canceled при ошибке или отмене. Выполняется ограниченным по времени
// контекстом даже после отмены основного.
func (j *Journal) FinishRun(ctx context.Context, runID int64, state string, runErr error) error {
	if runErr != nil {
		return j.finishRun(ctx, runID, state, runErr.Error())
	}
	return j.finishRun(ctx, runID, state, "")
}

func (j *Journal) finishRun(ctx context.Context, runID int64, state string, message string) error {
	// Статус canceled/failed фиксируется ограниченным по времени контекстом,
	// когда основной уже отменён.
	finishCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 5*time.Second)
	defer cancel()
	tx, err := j.db.BeginTx(finishCtx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	_, err = tx.ExecContext(finishCtx,
		fmt.Sprintf(`UPDATE %s.import_runs SET state = $2, finished_at = now(), error = NULLIF($3, '') WHERE id = $1`, Schema),
		runID, string(state), message)
	if err == nil && state == "ready" {
		_, err = tx.ExecContext(finishCtx, `UPDATE gar_control.datasets d SET
   applied_release=CASE WHEN COALESCE(jsonb_array_length(NULLIF(r.options->'regions','null'::jsonb)),0)=0 AND COALESCE(jsonb_array_length(NULLIF(r.options->'kinds','null'::jsonb)),0)=0 AND COALESCE(jsonb_array_length(NULLIF(r.options->'sources','null'::jsonb)),0)=0 THEN COALESCE(r.target_release,d.applied_release) ELSE d.applied_release END,
   source_release=GREATEST(COALESCE(d.source_release,''),COALESCE(r.target_release,'')),
   pending_digest=NULL FROM gar_control.import_runs r WHERE r.id=$1 AND d.id=r.dataset_id AND (d.pending_digest IS NULL OR d.pending_digest=r.source_digest)`, runID)
	}
	if err == nil && state == "sampled" {
		_, err = tx.ExecContext(finishCtx, `UPDATE gar_control.datasets d SET pending_digest=NULL FROM gar_control.import_runs r WHERE r.id=$1 AND d.id=r.dataset_id AND d.pending_digest=r.source_digest`, runID)
	}
	if err == nil {
		err = tx.Commit()
	}

	if err != nil {
		return fmt.Errorf("control: закрытие запуска: %w", err)
	}
	return nil
}

// StartFile фиксирует файл в плане запуска; возвращает id и (для resume)
// подтверждённый номер последней записи.
func (j *Journal) StartFile(ctx context.Context, runID int64, entryPath string, entryIndex int, kind, source string, region int, entryDate, entrySequence string) (int64, int64, error) {
	var (
		fileID    int64
		committed int64
	)
	err := j.db.QueryRowContext(ctx,
		fmt.Sprintf(`INSERT INTO %s.import_files (run_id, entry_path, entry_index, kind, source, region, entry_date, entry_sequence)
			VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
			ON CONFLICT (run_id, entry_path) DO UPDATE SET state = 'loading', error = NULL
			RETURNING id, last_committed_record`, Schema),
		runID, entryPath, entryIndex, kind, source, region, entryDate, entrySequence).Scan(&fileID, &committed)
	if err != nil {
		return 0, 0, fmt.Errorf("control: регистрация файла %s: %w", entryPath, err)
	}
	return fileID, committed, nil
}

// CheckpointExec — исполнитель checkpoint-SQL в транзакции записи данных
// (реализуется адаптером поверх tx-клиента Ent).
type CheckpointExec interface {
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
}

// CommitFile — checkpoint-часть CommitBatch: вызывается адаптером записи
// В ТОЙ ЖЕ транзакции, что и запись данных. last_committed_record и
// committed_input продвигаются вместе с данными, атомарно.
func (j *Journal) CommitFile(ctx context.Context, exec CheckpointExec, fileID, lastCommittedRecord, committedInput int64) error {
	_, err := exec.ExecContext(ctx,
		fmt.Sprintf(`UPDATE %s.import_files
			SET last_committed_record = GREATEST(last_committed_record, $2),
				committed_input = GREATEST(committed_input, $3)
			WHERE id = $1`, Schema),
		fileID, lastCommittedRecord, committedInput)
	if err != nil {
		return fmt.Errorf("control: checkpoint файла: %w", err)
	}
	return nil
}

// FinishFile закрывает файл: complete означает полное чтение и проверку
// целостности (CRC ZIP), а не только число обработанных строк.
func (j *Journal) FinishFile(ctx context.Context, fileID, writeOps int64, integrityChecked bool, runErr error) error {
	state := "complete"
	message := ""
	if runErr != nil {
		state, message = "failed", runErr.Error()
	}
	_, err := j.db.ExecContext(ctx,
		fmt.Sprintf(`UPDATE %s.import_files
			SET state = $2, integrity_checked = $3, error = NULLIF($4, ''),
				decoded = GREATEST(decoded, (SELECT committed_input FROM %s.import_files WHERE id = $1))
			WHERE id = $1`, Schema, Schema),
		fileID, state, integrityChecked, message)
	if err != nil {
		return fmt.Errorf("control: закрытие файла: %w", err)
	}
	return nil
}

// CompleteFiles возвращает пути файлов, завершённых полным чтением
// с проверенной целостностью (для resume).
func (j *Journal) CompleteFiles(ctx context.Context, runID int64) (map[string]int64, error) {
	rows, err := j.db.QueryContext(ctx,
		fmt.Sprintf(`SELECT entry_path, last_committed_record FROM %s.import_files
			WHERE run_id = $1 AND state = 'complete' AND integrity_checked`, Schema),
		runID)
	if err != nil {
		return nil, fmt.Errorf("control: список завершённых файлов: %w", err)
	}
	defer rows.Close()
	result := make(map[string]int64)
	for rows.Next() {
		var path string
		var committed int64
		if err := rows.Scan(&path, &committed); err != nil {
			return nil, err
		}
		result[path] = committed
	}
	return result, rows.Err()
}

// RunSource возвращает digest и режим запуска (проверка при resume).
func (j *Journal) RunSource(ctx context.Context, runID int64) (digest, mode string, err error) {
	err = j.db.QueryRowContext(ctx,
		fmt.Sprintf(`SELECT source_digest, mode FROM %s.import_runs WHERE id = $1`, Schema),
		runID).Scan(&digest, &mode)
	if err != nil {
		return "", "", fmt.Errorf("control: запуск %d: %w", runID, err)
	}
	return digest, mode, nil
}

// LatestResumableRun возвращает id последнего незавершённого запуска
// с тем же digest (кандидат на возобновление).
func (j *Journal) LatestResumableRun(ctx context.Context, digest string) (int64, error) {
	var runID int64
	err := j.db.QueryRowContext(ctx,
		fmt.Sprintf(`SELECT id FROM %s.import_runs
			WHERE source_digest = $1 AND state IN ('failed', 'canceled', 'loading', 'planned')
			ORDER BY id DESC LIMIT 1`, Schema),
		digest).Scan(&runID)
	if err == sql.ErrNoRows {
		return 0, nil
	}
	if err != nil {
		return 0, err
	}
	return runID, nil
}

// AcquireDataWriteLock сериализует запись в один dataset: второй процесс
// получает ошибку и обязан перепроверить состояние (не продолжать молча).
func (j *Journal) AcquireDataWriteLock(ctx context.Context, schemaName string) (release func(), err error) {
	datasetID, err := j.ensureDataset(ctx, schemaName)
	if err != nil {
		return nil, err
	}
	return j.acquireDatasetLock(ctx, datasetID)
}

// acquireDatasetLock берёт advisory-блокировку записи в dataset на выделенном
// соединении; потеря соединения прекращает владение.
func (j *Journal) acquireDatasetLock(ctx context.Context, datasetID int64) (release func(), err error) {
	conn, err := j.db.Conn(ctx)
	if err != nil {
		return nil, fmt.Errorf("control: соединение для блокировки: %w", err)
	}
	var locked bool
	err = conn.QueryRowContext(ctx,
		"SELECT pg_try_advisory_lock($1)", datasetLockKey(datasetID)).Scan(&locked)
	if err != nil || !locked {
		conn.Close()
		if err != nil {
			return nil, err
		}
		return nil, fmt.Errorf("control: dataset %d уже записывается другим процессом", datasetID)
	}
	return func() {
		releaseCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 5*time.Second)
		defer cancel()
		_, _ = conn.ExecContext(releaseCtx, "SELECT pg_advisory_unlock($1)", datasetLockKey(datasetID))
		_ = conn.Close()
	}, nil
}

func datasetLockKey(datasetID int64) int64 {
	// 0x6761725F00000000 | id — стабильный ключ пространства блокировок.
	return int64(0x6761725F00000000) | datasetID
}

// RunOptions returns the original selection for resume validation.
func (j *Journal) RunOptions(ctx context.Context, runID int64) (string, error) {
	var options string
	err := j.db.QueryRowContext(ctx, fmt.Sprintf(`SELECT options FROM %s.import_runs WHERE id = $1`, Schema), runID).Scan(&options)
	return options, err
}

// ResumeRun resets the attempt status while preserving completed files and checkpoints.
func (j *Journal) ResumeRun(ctx context.Context, runID int64) error {
	_, err := j.db.ExecContext(ctx, fmt.Sprintf(`UPDATE %s.import_runs SET state = 'loading', finished_at = NULL, error = NULL WHERE id = $1`, Schema), runID)
	return err
}

// ReadyRun finds a completed import with the same content and selection under the dataset lock.
func (j *Journal) ReadyRun(ctx context.Context, digest string, options importjob.Options) (int64, error) {
	rows, err := j.db.QueryContext(ctx, `SELECT id, options FROM gar_control.import_runs WHERE source_digest=$1 AND state='ready' ORDER BY id DESC`, digest)
	if err != nil {
		return 0, err
	}
	defer rows.Close()
	for rows.Next() {
		var id int64
		var saved string
		if err := rows.Scan(&id, &saved); err != nil {
			return 0, err
		}
		if importjob.MatchesSelection(saved, options) {
			return id, nil
		}
	}
	return 0, rows.Err()
}

// PrepareRelease reserves the archive before any writes. Failed runs keep the reservation.
func (j *Journal) PrepareRelease(ctx context.Context, digest, mode, base, target string) error {
	var applied, pending, observed string
	if err := j.db.QueryRowContext(ctx, `SELECT COALESCE(applied_release,''), COALESCE(pending_digest,''), COALESCE(source_release,'') FROM gar_control.datasets WHERE schema_name='gar'`).Scan(&applied, &pending, &observed); err != nil {
		return err
	}
	if pending != "" && pending != digest {
		return fmt.Errorf("%w: требуется закончить архив %s", importjob.ErrReleaseBlocked, pending)
	}
	if observed != "" && target < observed {
		return fmt.Errorf("%w: выпуск %s старее загруженных данных %s", importjob.ErrReleaseOrder, target, observed)
	}
	if err := importjob.ValidateReleaseOrder(mode, applied, base, target); err != nil {
		return err
	}
	_, err := j.db.ExecContext(ctx, `UPDATE gar_control.datasets SET pending_digest=$1 WHERE schema_name='gar'`, digest)
	return err
}

func (j *Journal) SetRunRelease(ctx context.Context, id int64, base, target string) error {
	_, err := j.db.ExecContext(ctx, `UPDATE gar_control.import_runs SET base_release=NULLIF($2,''), target_release=NULLIF($3,'') WHERE id=$1`, id, base, target)
	return err
}
